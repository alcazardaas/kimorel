import records from './exercises.json' with { type: 'json' };
import { exerciseRegistrySchema } from '@kimorel/schemas';
import { findExercise, filterExercises } from '@kimorel/core';
import type { ExerciseFilter } from '@kimorel/core';
import type { Exercise } from '@kimorel/core';
export const exercises: readonly Exercise[] =
  exerciseRegistrySchema.parse(records);
export const getExercise = (id: string): Exercise | undefined =>
  findExercise(exercises, id);
export const queryExercises = (filter: ExerciseFilter): Exercise[] =>
  filterExercises(exercises, filter);

/** Preview references only: human asset approval is enforced separately at release. */
export const previewAnimationManifest = exercises.flatMap((exercise) =>
  exercise.animation
    ? [{ exerciseId: exercise.id, ...exercise.animation }]
    : [],
);
